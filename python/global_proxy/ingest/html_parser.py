"""
Advanced HTML Parser — BeautifulSoup4 Integration
Sophisticated SERP feature detection and parsing
"""

from bs4 import BeautifulSoup
import re
from typing import Dict, List, Optional

class AdvancedHTMLParser:
    """
    Advanced HTML Parser for SERP analysis
    - BeautifulSoup4 integration
    - Multi-country support
    - SERP feature detection
    - Competitor analysis
    """
    
    # SERP Feature patterns
    SERP_PATTERNS = {
        "ai_overview": [
            "AI Overview",
            "Generative AI",
            "AI-powered answer",
            "Generated by AI"
        ],
        "featured_snippet": [
            "Featured Snippet",
            "Position 0",
            "Direct answer",
            "Top result"
        ],
        "shopping": [
            "Shopping",
            "Product listing",
            "Buy now",
            "Price",
            "Shop"
        ],
        "knowledge_panel": [
            "Knowledge Panel",
            "Knowledge Graph",
            "Information panel"
        ],
        "local_pack": [
            "Local Pack",
            "Map pack",
            "Places",
            "Nearby"
        ],
        "video_carousel": [
            "Video",
            "YouTube",
            "Watch"
        ],
        "image_pack": [
            "Images",
            "Image results",
            "Pictures"
        ]
    }
    
    # Country-specific patterns
    COUNTRY_PATTERNS = {
        "US": {"gl": "us", "hl": "en", "tld": ".com"},
        "UK": {"gl": "uk", "hl": "en", "tld": ".co.uk"},
        "DE": {"gl": "de", "hl": "de", "tld": ".de"},
        "BR": {"gl": "br", "hl": "pt", "tld": ".com.br"},
        "IN": {"gl": "in", "hl": "en", "tld": ".in"},
        "JP": {"gl": "jp", "hl": "ja", "tld": ".co.jp"},
        "AU": {"gl": "au", "hl": "en", "tld": ".com.au"},
        "FR": {"gl": "fr", "hl": "fr", "tld": ".fr"},
        "CA": {"gl": "ca", "hl": "en", "tld": ".ca"},
        "ES": {"gl": "es", "hl": "es", "tld": ".es"}
    }
    
    def __init__(self):
        self.soup = None
    
    def parse_html(self, html: str) -> BeautifulSoup:
        """Parse HTML with BeautifulSoup4"""
        self.soup = BeautifulSoup(html, 'html.parser')
        return self.soup
    
    def extract_serp_results(self, html: str) -> List[Dict]:
        """Extract SERP results from HTML"""
        soup = self.parse_html(html)
        results = []
        
        # Find all search result divs
        for div in soup.find_all('div', class_=re.compile('g|tF2Cxc')):
            result = {}
            
            # Extract title
            title_tag = div.find('h3')
            if title_tag:
                result['title'] = title_tag.get_text(strip=True)
            
            # Extract URL
            link = div.find('a')
            if link and link.get('href'):
                result['url'] = link['href']
            
            # Extract snippet
            snippet = div.find('span', class_=re.compile('aCOpRe|st'))
            if snippet:
                result['snippet'] = snippet.get_text(strip=True)
            
            # Extract domain
            if 'url' in result:
                domain = re.search(r'https?://([^/]+)', result['url'])
                if domain:
                    result['domain'] = domain.group(1)
            
            if result:
                results.append(result)
        
        return results
    
    def detect_serp_features(self, html: str) -> Dict[str, bool]:
        """Detect SERP features in HTML"""
        features = {}
        
        for feature, patterns in self.SERP_PATTERNS.items():
            features[feature] = any(pattern.lower() in html.lower() for pattern in patterns)
        
        return features
    
    def extract_competitors(self, results: List[Dict]) -> List[Dict]:
        """Extract and rank competitors"""
        competitors = []
        
        for i, result in enumerate(results[:10]):
            competitor = {
                "rank": i + 1,
                "title": result.get("title", ""),
                "url": result.get("url", ""),
                "domain": result.get("domain", ""),
                "snippet": result.get("snippet", "")[:100]
            }
            competitors.append(competitor)
        
        return competitors
    
    def analyze_movement(self, current: List[Dict], previous: List[Dict]) -> List[Dict]:
        """Analyze competitor movement between snapshots"""
        movement = []
        
        prev_domains = {c.get("domain", ""): c for c in previous}
        
        for comp in current:
            domain = comp.get("domain", "")
            if domain in prev_domains:
                prev_rank = prev_domains[domain].get("rank", 0)
                curr_rank = comp.get("rank", 0)
                
                if curr_rank < prev_rank:
                    comp["movement"] = "up"
                    comp["change"] = prev_rank - curr_rank
                elif curr_rank > prev_rank:
                    comp["movement"] = "down"
                    comp["change"] = prev_rank - curr_rank
                else:
                    comp["movement"] = "stable"
                    comp["change"] = 0
            else:
                comp["movement"] = "new"
                comp["change"] = 0
            
            movement.append(comp)
        
        return movement
